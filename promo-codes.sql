-- BAZE CHINA: secure promo codes and order discounts
-- Run this migration in Supabase SQL Editor after create_store_order is installed.
create table if not exists public.promo_codes (
 id bigint generated by default as identity primary key,
 code text not null unique check (code = upper(code) and code ~ '^[A-Z0-9_-]{3,32}$'),
 discount_percent integer not null check (discount_percent between 1 and 80),
 is_active boolean not null default true,
 max_uses integer null check (max_uses is null or max_uses > 0),
 used_count integer not null default 0 check (used_count >= 0),
 expires_at date null,
 created_at timestamptz not null default now()
);
alter table public.promo_codes enable row level security;
drop policy if exists "Admins manage promo codes" on public.promo_codes;
create policy "Admins manage promo codes" on public.promo_codes for all to authenticated
using (exists (select 1 from public.admin_users au where au.user_id = auth.uid()))
with check (exists (select 1 from public.admin_users au where au.user_id = auth.uid()));
create or replace function public.validate_store_promo(p_code text, p_subtotal numeric)
returns jsonb language plpgsql security definer set search_path = public as $$
declare p public.promo_codes%rowtype;
begin
 if nullif(upper(trim(p_code)), '') is null then return jsonb_build_object('valid', false, 'message', 'Введи промокод.'); end if;
 select * into p from public.promo_codes where code=upper(trim(p_code)) and is_active and (expires_at is null or expires_at>=current_date) and (max_uses is null or used_count<max_uses);
 if not found then return jsonb_build_object('valid', false, 'message', 'Промокод недействителен или уже использован.'); end if;
 if coalesce(p_subtotal,0)<=0 then return jsonb_build_object('valid', false, 'message', 'Корзина пуста.'); end if;
 return jsonb_build_object('valid',true,'code',p.code,'discount_percent',p.discount_percent);
end; $$;
create or replace function public.create_store_order_with_promo(p_customer_name text,p_phone text,p_address text,p_items jsonb,p_email text,p_comment text,p_promo_code text)
returns bigint language plpgsql security definer set search_path = public as $$
declare v_order_id bigint; v_subtotal numeric; v_discount numeric:=0; v_promo public.promo_codes%rowtype;
begin
 if nullif(trim(p_promo_code),'') is not null then
  select * into v_promo from public.promo_codes where code=upper(trim(p_promo_code)) and is_active and (expires_at is null or expires_at>=current_date) and (max_uses is null or used_count<max_uses) for update;
  if not found then raise exception 'PROMO_INVALID: Промокод недействителен или лимит активаций исчерпан.'; end if;
 end if;
 v_order_id:=public.create_store_order(p_customer_name,p_phone,p_address,p_items,p_email,p_comment);
 if nullif(trim(p_promo_code),'') is not null then
  select total into v_subtotal from public.orders where id=v_order_id for update;
  v_discount:=round(v_subtotal*v_promo.discount_percent/100,2);
  update public.orders set total=greatest(0,v_subtotal-v_discount), customer_comment=concat_ws(E'\n',nullif(customer_comment,''),'Промокод '||v_promo.code||': скидка '||v_promo.discount_percent||'% (−'||v_discount||' ₽)') where id=v_order_id;
  update public.promo_codes set used_count=used_count+1 where id=v_promo.id;
 end if;
 return v_order_id;
end; $$;
grant execute on function public.validate_store_promo(text,numeric) to anon,authenticated;
grant execute on function public.create_store_order_with_promo(text,text,text,jsonb,text,text,text) to anon,authenticated;
